// 기록을 저장하면 우리 강아지가 한마디 + 알아 두면 좋은 한 줄.
// 걱정되는 기록(증상, 묽은 변, 입맛 없음)에는 축하 효과 없이 차분하게 — 진단이나 단정은 하지 않는다.
const BAD_STOOL = ["무름", "설사", "딱딱함", "피 섞임"];

export function reactionFor(rec) {
  const d = rec.data || {};
  switch (rec.type) {
    case "weight":
      return { line: "몸무게 적어 줬구나! 꾸준히 재면 변화가 잘 보여.", tip: "체중은 같은 시간대에 같은 방법으로 재면 비교가 정확해요. 아침 밥 먹기 전이 좋아요." };
    case "symptom":
      return { concern: true, line: "알려 줘서 고마워. 나 계속 지켜봐 줘.", tip: "언제부터, 하루 몇 번인지 적어 두면 진료 때 큰 도움이 돼요. 숨이 가쁘거나, 기운이 갑자기 없거나, 피가 보이면 기다리지 말고 바로 병원에 연락해 주세요." };
    case "meal":
      return d.appetite === "평소보다 적음"
        ? { concern: true, line: "오늘은 입맛이 별로였어…", tip: "식욕이나 물 마시는 양이 며칠째 평소와 다르면 진료 때 꼭 말해 주세요. 하루 넘게 거의 안 먹으면 병원에 문의해 주세요." }
        : { line: "맛있게 먹었어! 적어 줘서 고마워.", tip: "식욕과 물 마시는 양은 컨디션을 가장 먼저 보여 주는 신호예요. 평소 양을 알아 두면 변화를 바로 알아챌 수 있어요." };
    case "potty":
      if (d.photoFlags?.length) return { concern: true, line: "사진에 마음 쓰이는 게 보였대…", tip: "사진만으로는 정확하지 않지만, 피나 기생충처럼 보이는 게 있으면 동물병원에 사진을 보여 주며 문의해 주세요. 기록은 '병원용 기록'에도 들어가요." };
      return BAD_STOOL.includes(d.stool)
        ? { concern: true, line: "배가 좀 불편했나 봐…", tip: "변의 모양·색·횟수는 장 건강을 보는 가장 쉬운 단서예요. 피가 섞이거나 설사가 하루 넘게 이어지면 병원에 문의해 주세요." }
        : { line: "시원하다! 적어 줘서 고마워.", tip: "배변 기록이 쌓이면 평소 패턴이 보여서, 달라졌을 때 바로 알 수 있어요." };
    case "vet":
      return { line: "병원 다녀왔구나. 오늘 수고했어!", tip: "수의사 설명은 그날 적어 두는 게 가장 정확해요. 다음 진료 때 '병원용 기록'으로 바로 보여 줄 수 있어요." };
    case "condition":
      return { line: "내 컨디션 기억해 줘서 고마워.", tip: "활동량과 잠이 며칠째 달라지면 몸이 보내는 신호일 수 있어요. 나이가 들수록 더 중요해요." };
    case "daily":
      if (d.kind === "산책") return { line: "산책 최고! 또 가자!", tip: "산책 시간과 활동 정도를 적어 두면 체중 변화와 같이 볼 수 있어요." };
      if (d.kind === "양치") return { line: "이 닦았어! 입이 상쾌해.", tip: "양치는 매일 하는 게 가장 좋아요. 잇몸이 빨갛거나 입 냄새가 심해지면 컨디션 기록에 같이 적어 주세요." };
      return { line: "오늘도 같이 보내서 좋아!", tip: "작은 일상 기록도 쌓이면 우리 아이의 평소 모습이 돼요." };
    case "life":
      return d.kind === "예방접종"
        ? { line: "주사 맞느라 고생했어. 나 용감했지?", tip: "접종 날짜를 적어 두면 다음 접종을 놓치지 않아요. 접종 당일은 무리한 산책과 목욕을 피해 주세요." }
        : { line: "우리 추억이 하나 늘었다!", tip: "기념일과 특별한 일은 나중에 성장 기록으로 다시 볼 수 있어요." };
    case "media":
      return { line: "나 잘 나왔어?", tip: "같은 자리, 같은 자세로 가끔 찍어 두면 체형이나 털 상태 변화를 비교하기 좋아요." };
    default:
      return { line: "적어 줘서 고마워!", tip: "" };
  }
}
