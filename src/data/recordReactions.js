// 어떤 걱정 기록인지(아니면 undefined)
function concernOf(rec) {
  const d = rec.data || {};
  if (rec.type === "symptom") return "symptom";
  if (rec.type === "meal" && d.appetite === "평소보다 적음") return "meal";
  if (rec.type === "potty" && (BAD_STOOL.includes(d.stool) || d.stoolSigns?.length || BAD_COLOR.includes(d.stoolColor) || d.photoFlags?.length || d.flags?.length)) return "potty";
  if (rec.type === "condition" && (Object.values(d.check || {}).includes("많이 다름") || d.flags?.length)) return "condition";
}

function poolKey(rec) {
  const kind = rec.data?.kind;
  if (rec.type === "daily") return LINES[`daily:${kind}`] ? `daily:${kind}` : "daily:기타";
  if (rec.type === "life") return LINES[`life:${kind}`] ? `life:${kind}` : "life:추억";
  return LINES[rec.type] ? rec.type : "daily:기타";
}

// 셔플 백 — 묶음마다 남은 순서를 저장해 두고 하나씩 꺼낸다. 다 꺼내면 다시 섞되, 직전에 나온 건 맨 처음에 오지 않게.
// localStorage가 없으면(Node 테스트 등) readJSON/writeJSON이 조용히 실패하고 메모리(bags)만 쓴다.
const BAG_KEY = "dogcare-reaction-bag-v1";
let bags = null;
function draw(key, pool) {
  bags ||= readJSON(BAG_KEY, {}) || {};
  let b = bags[key];
  if (!b || b.n !== pool.length || !b.q?.length) {
    const q = pool.map((_, i) => i);
    for (let i = q.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [q[i], q[j]] = [q[j], q[i]];
    }
    if (q.length > 1 && q[q.length - 1] === b?.last) [q[0], q[q.length - 1]] = [q[q.length - 1], q[0]];
    b = { n: pool.length, q };
  }
  const i = b.q.pop();
  bags[key] = { n: b.n, q: b.q, last: i };
  writeJSON(BAG_KEY, bags);
  return pool[i];
}

// 받침 있으면 "은/이", 없으면 "는/가"
const hasBatchim = (name) => {
  const c = name.charCodeAt(name.length - 1) - 0xac00;
  return c >= 0 && c <= 11171 && c % 28 !== 0;
};
function fill(line, { dogName, n, what } = {}) {
  const name = (dogName || "").trim();
  return line
    .replace("{N은}", name ? name + (hasBatchim(name) ? "은" : "는") : "나는")
    .replace("{N이}", name ? name + (hasBatchim(name) ? "이" : "가") : "내가")
    .replaceAll("{n}", n)
    .replaceAll("{what}", what);
}

// 체중 기록은 at 대신 measuredAt으로 돌아온다
const atOf = (r) => r.at || r.measuredAt?.slice(0, 16);
function timeSlot(at) {
  const h = Number(at?.slice(11, 13));
  if (!at || Number.isNaN(h)) return null;
  return h >= 5 && h <= 10 ? "아침" : h >= 11 && h <= 16 ? "낮" : h >= 17 && h <= 20 ? "저녁" : "밤";
}
const isWeekend = (at) => {
  const day = at ? new Date(`${at.slice(0, 10)}T00:00:00`).getDay() : NaN;
  return day === 0 || day === 6;
};

// ctx: { streak?: 같은 종류 연속 기록 일수, first?: 이 종류 첫 기록, dogName? } — 모두 없어도 된다
export function reactionFor(rec, ctx = {}) {
  const concern = concernOf(rec);
  if (concern) {
    const tip = concern === "potty" && rec.data?.photoFlags?.length ? PHOTO_TIP : draw(`tip:calm:${concern}`, CALM_TIPS[concern]);
    return { concern: true, line: fill(draw(`calm:${concern}`, CALM[concern]), ctx), tip };
  }
  const key = poolKey(rec);
  const tip = draw(`tip:${key}`, TIPS[key]);
  const what = WHAT[rec.type] || rec.data?.kind || "일상";
  let line;
  if (QUIET.has(key)) return { quiet: true, line: fill(draw(key, LINES[key]), ctx), tip };
  if (ctx.first) line = draw("first", FIRST_LINES);
  else if (ctx.streak >= 2 && !NO_STREAK.has(key) && Math.random() < 0.4) line = draw("streak", STREAK_LINES);
  else if (Math.random() < 0.25) {
    const at = atOf(rec);
    const slot = isWeekend(at) && Math.random() < 0.5 ? "주말" : timeSlot(at);
    if (slot) line = draw(`time:${slot}`, TIME_LINES[slot]);
  }
  line ||= draw(key, LINES[key]);
  return { line: fill(line, { ...ctx, n: ctx.streak, what }), tip };
}

// 화면에서 쓰는 상황 정보 — list는 이 기록이 이미 들어 있는 전체 기록(getTimeline)
export function reactionContext(rec, list = []) {
  const kindOf = (r) => (r.type === "daily" || r.type === "life" ? `${r.type}:${r.data?.kind}` : r.type);
  const same = list.filter((r) => kindOf(r) === kindOf(rec));
  const days = new Set(same.map((r) => r.at?.slice(0, 10)));
  let streak = 0;
  for (let d = atOf(rec)?.slice(0, 10); d && days.has(d); d = toDateKey(addDays(new Date(`${d}T00:00:00`), -1))) streak++;
  return { first: same.every((r) => r.id === rec.id), streak };
}
